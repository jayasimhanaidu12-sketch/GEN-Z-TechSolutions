function updateCarbonDisplay(saved) {
  const maxCO2 = 10;
  const pct = Math.min(saved / maxCO2, 1);
  const circumference = 2 * Math.PI * 60;
  const offset = circumference * (1 - pct);
  const ring = document.getElementById('carbonRingFill');
  if (ring) ring.style.strokeDashoffset = offset;
  const valEl = document.getElementById('carbonValue');
  if (valEl) valEl.textContent = saved.toFixed(1);
  const treesEl = document.getElementById('treesEquiv');
  if (treesEl) treesEl.textContent = Math.round(saved * 50);
  const carsEl = document.getElementById('carsEquiv');
  if (carsEl) carsEl.textContent = (saved / 4.6).toFixed(1);
  const flightsEl = document.getElementById('flightsEquiv');
  if (flightsEl) flightsEl.textContent = Math.round(saved / 0.9);
}

