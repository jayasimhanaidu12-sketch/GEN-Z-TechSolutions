// 14. ANIMATED COUNTERS
// ═════════════════════════════════════════════════════════════
function initAnimatedCounters() {
  const counters = document.querySelectorAll('.stat-number[data-count]');
  let animated = false;
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting && !animated) { animated = true; counters.forEach(c => animateCounter(c)); }
    });
  }, { threshold: 0.5 });
  const statsBar = document.querySelector('.impact-bar');
  if (statsBar) observer.observe(statsBar);
}

function animateCounter(el) {
  const target = parseInt(el.dataset.count, 10);
  const prefix = el.dataset.prefix || '';
  const suffix = el.dataset.suffix || '';
  const duration = 2000;
  const startTime = performance.now();
  if (target === 0) { el.textContent = prefix + '0' + suffix; return; }
  function update(now) {
    const elapsed = now - startTime;
    const progress = Math.min(elapsed / duration, 1);
    const eased = 1 - Math.pow(1 - progress, 3);
    const current = Math.round(target * eased);
    el.textContent = prefix + current.toLocaleString('en-IN') + (progress >= 1 && suffix !== '%' ? '+' : '');
    if (suffix) el.textContent = prefix + current.toLocaleString('en-IN') + suffix;
    if (progress < 1) requestAnimationFrame(update);
  }
  requestAnimationFrame(update);
}

